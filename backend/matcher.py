def _normalize(text: str) -> str:
    text = unicodedata.normalize("NFKC", text or "")
    text = text.strip().lower()
    text = re.sub(r"[\s，。、；：？！,.;:?!\(\)\[\]{}「」『』“”\"'·—…-]+", "", text)
    return text


def _char_bigrams(s: str) -> set[str]:
    if len(s) < 2:
        return {s} if s else set()
    return {s[i : i + 2] for i in range(len(s) - 1)}


def _overlap(a: str, b: str) -> float:
    if not a or not b:
        return 0.0
    ga, gb = _char_bigrams(a), _char_bigrams(b)
    if not ga or not gb:
        return 1.0 if a == b else 0.0
    inter = len(ga & gb)
    return inter / max(len(ga), len(gb))


def _synonym_expand(token: str) -> set[str]:
    out = {token}
    for group in SYNONYM_GROUPS:
        if token in group:
            out |= group
    return out


def is_correct_answer(user_input: str, accepted: list[str], threshold: float = 0.72) -> dict:
    """Return {correct, score, matched, reason}."""
    raw = (user_input or "").strip()
    if not raw:
        return {"correct": False, "score": 0.0, "matched": "", "reason": "empty"}

    u = _normalize(raw)
    # reject pure English answers for Chinese-meaning mode
    if u and not re.search(r"[一-鿿]", u) and re.fullmatch(r"[a-z]+", u):
        return {"correct": False, "score": 0.0, "matched": "", "reason": "english"}

    best_score = 0.0
    best_match = ""
    for ans in accepted:
        a = _normalize(ans)
        if not a:
            continue
        score = 0.0
        reason = ""
        if u == a:
            score, reason = 1.0, "exact"
        elif u in a or a in u:
            # containment: strong but not perfect if much shorter
            shorter, longer = (u, a) if len(u) <= len(a) else (a, u)
            ratio = len(shorter) / max(len(longer), 1)
            score = 0.88 if ratio >= 0.55 else 0.78
            reason = "contain"
        else:
            # synonym
            u_tokens = _synonym_expand(u)
            a_tokens = _synonym_expand(a)
            if u_tokens & a_tokens:
                score, reason = 0.95, "synonym"
            else:
                score = _overlap(u, a)
                reason = "fuzzy"
                # boost if core meaning chars shared heavily
                if score >= 0.9:
                    score = min(0.93, score)
        if score > best_score:
            best_score = score
            best_match = ans

    correct = best_score >= threshold
    return {
        "correct": correct,
        "score": round(best_score, 3),
        "matched": best_match,
        "reason": "pass" if correct else "fail",
    }


def build_choices(correct_def: str, distractor_pool: list[str], n: int = 4) -> list[dict]:
    """Build n choices including the correct one. Returns shuffled list of {text, correct}."""
    import random

    correct = (correct_def or "").strip()
    pool = []
    seen = {_normalize(correct)}
    for d in distractor_pool:
        d = (d or "").strip()
        if not d:
            continue
        key = _normalize(d)
        if key in seen:
            continue
        # skip near-duplicates of correct
        if _overlap(key, _normalize(correct)) >= 0.85:
            continue
        seen.add(key)
        pool.append(d)

    random.shuffle(pool)
    picks = pool[: max(0, n - 1)]
    # if not enough distractors, pad with generic wrong-looking placeholders from pool cycles
    while len(picks) < n - 1 and pool:
        picks.append(pool[len(picks) % len(pool)])

    choices = [{"text": correct, "correct": True}] + [
        {"text": d, "correct": False} for d in picks
    ]
    random.shuffle(choices)
    return choices[:n]
